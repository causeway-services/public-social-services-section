#!/usr/bin/env node

// Compile the prior newsroom knowledge and the implementation actually used
// by Koios into the runtime module sent to the independent editor. The live
// runtime must not silently lose this context merely because it is deployed
// without the monorepo around it.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SITE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(SITE_ROOT, "src/generated/editorial-pipeline-context.mts");
const BUNDLE = join(SITE_ROOT, "content/editorial-context/pipeline-context.json");
const PRODUCING_CONTENT = resolve(SITE_ROOT, "../../../../../red-cup-engineering/src/content/assets/legacy/2026-07-03-producing-content");

const SOURCES = Object.freeze([
  ["prior-art/agentic-newsroom", resolve(SITE_ROOT, "../../dev/content/notes/2026/06/01/agentic-newsroom.md")],
  ["prior-art/news-topology", resolve(SITE_ROOT, "../../dev/content/notes/2026/06/01/news-topology.md")],
  ["prior-art/claims-to-prose", resolve(SITE_ROOT, "../../dev/content/notes/2026/06/01/claims-to-prose.md")],
  ["prior-art/accountable-attention", resolve(SITE_ROOT, "../../dev/content/notes/2026/06/01/accountable-attention.md")],
  ["newsroom/researching-skill", join(SITE_ROOT, "working/researching/SKILL.md")],
  ["newsroom/researching-script", join(SITE_ROOT, "working/researching/scripts/new-brief.mjs")],
  ["newsroom/writing-skill", join(SITE_ROOT, "working/writing/SKILL.md")],
  ["newsroom/writing-script", join(SITE_ROOT, "working/writing/scripts/new-post.mjs")],
  ["newsroom/editing-skill", join(SITE_ROOT, "working/editing/SKILL.md")],
  ["newsroom/editing-script", join(SITE_ROOT, "working/editing/scripts/lint-post.mjs")],
  ["production/cultivate", join(PRODUCING_CONTENT, "src/content-farm/cultivate.mts")],
  ["production/newsroom", join(PRODUCING_CONTENT, "src/content-farm/newsroom.mts")],
  ["production/article-topology", join(PRODUCING_CONTENT, "src/topology/article.mts")],
  ["production/inference-adapter", join(PRODUCING_CONTENT, "src/computer/ask.mts")],
]);

function validate(entries) {
  if (!Array.isArray(entries) || entries.length !== SOURCES.length) throw new Error("editorial context bundle has the wrong source count");
  for (const [index, entry] of entries.entries()) {
    if (entry?.sourceId !== SOURCES[index][0] || typeof entry.content !== "string" || entry.content.trim() === "") throw new Error(`editorial context bundle source mismatch at ${index}`);
    const observed = `sha256:${createHash("sha256").update(entry.content).digest("hex")}`;
    if (entry.digest !== observed) throw new Error(`editorial context bundle digest mismatch: ${entry.sourceId}`);
  }
  return entries;
}
function writeAtomic(path, bytes) {
  mkdirSync(dirname(path), { recursive: true });
  try { if (readFileSync(path, "utf8") === bytes) return; } catch { /* first build */ }
  const temporary = `${path}.${process.pid}.tmp`;
  try { writeFileSync(temporary, bytes, { encoding: "utf8", mode: 0o600 }); renameSync(temporary, path); }
  finally { rmSync(temporary, { force: true }); }
}

const sourcesAvailable = SOURCES.every(([, path]) => existsSync(path));
const entries = validate(sourcesAvailable
  ? SOURCES.map(([sourceId, path]) => {
      const content = readFileSync(path, "utf8");
      return { sourceId, digest: `sha256:${createHash("sha256").update(content).digest("hex")}`, content };
    })
  : JSON.parse(readFileSync(BUNDLE, "utf8")));
if (sourcesAvailable) writeAtomic(BUNDLE, `${JSON.stringify(entries, null, 2)}\n`);
const totalBytes = entries.reduce((sum, entry) => sum + Buffer.byteLength(entry.content), 0);
const moduleBytes = `// Generated by scripts/prepare-editorial-pipeline-context.mjs.\n// Exact source bytes are bundled so the deployed editor receives the same context as the monorepo build.\nexport const EDITORIAL_PIPELINE_CONTEXT = Object.freeze(${JSON.stringify(entries, null, 2)});\nexport const EDITORIAL_PIPELINE_CONTEXT_TOTAL_BYTES = ${totalBytes};\n`;

writeAtomic(OUTPUT, moduleBytes);
